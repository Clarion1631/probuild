#!/usr/bin/env node
// Snapshots the production objects that Prisma's migrate/introspect engine
// cannot represent, into prisma/prisma-blind-spots.json.
//
// Prisma silently omits these from `migrate diff` output. They therefore do not
// appear in a generated baseline, do not appear in any drift check built on
// `migrate diff`, and vanish without a word from any database built from the
// committed migrations. Production currently has three such classes:
//
//   partialIndexes  – 7, three of them UNIQUE and carrying real invariants
//   checkConstraints – 6, two of them XOR ownership invariants
//   rlsTables       – 26 tables with RLS enabled (and no policies)
//
// The baseline migration ends with a generated block built from this file, and
// scripts/check-migrations-match.mjs asserts a migrated database matches it
// exactly. Regenerate with:
//
//   node scripts/snapshot-prisma-blind-spots.mjs --write
//
// against a DATABASE_URL pointing at production (read-only; it only SELECTs
// from catalog tables).
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const OUT = path.join(ROOT, 'prisma', 'prisma-blind-spots.json')

const url = process.env.DATABASE_URL
if (!url) {
  console.error('snapshot-prisma-blind-spots: set DATABASE_URL')
  process.exit(2)
}

const { PrismaClient } = await import('@prisma/client')
const db = new PrismaClient({ datasources: { db: { url } } })
const q = (sql) => db.$queryRawUnsafe(sql)

// pg_get_indexdef / pg_get_constraintdef give the canonical, normalised form the
// server itself will report back, so a later comparison is exact rather than
// textual-with-hope.
const partialIndexes = await q(`
  SELECT c.relname AS name, pg_get_indexdef(i.indexrelid) AS def
    FROM pg_index i
    JOIN pg_class c ON c.oid = i.indexrelid
   WHERE c.relnamespace = 'public'::regnamespace
     AND i.indpred IS NOT NULL
   ORDER BY c.relname`)

const checkConstraints = await q(`
  SELECT conname AS name, conrelid::regclass::text AS "table",
         pg_get_constraintdef(oid) AS def
    FROM pg_constraint
   WHERE connamespace = 'public'::regnamespace
     AND contype IN ('c', 'x')
   ORDER BY conname`)

const rlsTables = await q(`
  SELECT relname AS name, relforcerowsecurity AS forced
    FROM pg_class
   WHERE relnamespace = 'public'::regnamespace AND relrowsecurity
   ORDER BY relname`)

const policies = await q(`
  SELECT tablename AS "table", policyname AS name
    FROM pg_policies WHERE schemaname = 'public' ORDER BY policyname`)

await db.$disconnect()

const snapshot = {
  _comment:
    'Generated by scripts/snapshot-prisma-blind-spots.mjs. Production objects Prisma cannot represent. Do not hand-edit.',
  capturedAt: '2026-08-14',
  partialIndexes,
  checkConstraints,
  rlsTables,
  policies,
}

if (process.argv.includes('--write')) {
  writeFileSync(OUT, JSON.stringify(snapshot, null, 2) + '\n', 'utf8')
  console.log(`wrote ${OUT}`)
} else {
  console.log(JSON.stringify(snapshot, null, 2))
}
